package org.jscratch.cli

import org.jscratch.compiler.JScratch
import org.jscratch.compiler.jvm.RhinoProjectJson
import java.io.File
import kotlin.system.exitProcess

private const val USAGE = """
jScratch: compiles Scratch 3 projects (.sb3) into executable JARs.

Usage: jscratch <project.sb3 | project link | project ID> [options]

The input is a local .sb3 file, or a shared project on scratch.mit.edu given by
its link (https://scratch.mit.edu/projects/<id>) or its numeric ID.

Options:
  -o, --output <file>   Output JAR (default: <project>.jar next to the input,
                        or <id>.jar in the current directory for a download)
  --save-sb3 <file>     Also save a downloaded project as an .sb3 file
  --run                 Run the JAR after compiling
  --dump                Print the generated bytecode (ASM Textifier)
  --no-runtime          Emit only the generated classes and assets, without the runtime
  -h, --help            Show this help
"""

fun main(args: Array<String>) {
    var input: String? = null
    var output: File? = null
    var saveSb3: File? = null
    var run = false
    var dump = false
    var includeRuntime = true

    var i = 0
    while (i < args.size) {
        when (val a = args[i]) {
            "-h", "--help" -> {
                println(USAGE.trim())
                return
            }
            "-o", "--output" -> {
                i++
                if (i >= args.size) fail("missing value for $a")
                output = File(args[i])
            }
            "--save-sb3" -> {
                i++
                if (i >= args.size) fail("missing value for $a")
                saveSb3 = File(args[i])
            }
            "--run" -> run = true
            "--dump" -> dump = true
            "--no-runtime" -> includeRuntime = false
            else -> {
                if (a.startsWith("-")) fail("unknown option $a")
                if (input != null) fail("only one input is supported")
                input = a
            }
        }
        i++
    }

    val arg = input ?: fail("no input given\n\n${USAGE.trim()}")
    val json = RhinoProjectJson()
    // A local file wins over a project ID, so a file named "123" still compiles.
    val inFile = File(arg)
    val projectId = if (inFile.isFile) null else ScratchDownloader.projectId(arg)
    val sb3: ByteArray
    val outFile: File
    if (projectId == null) {
        if (!inFile.isFile) fail("${inFile.path} does not exist and is not a Scratch project link or ID")
        if (saveSb3 != null) fail("--save-sb3 only applies when downloading a project")
        sb3 = inFile.readBytes()
        outFile = output ?: File(inFile.parentFile ?: File("."), inFile.nameWithoutExtension + ".jar")
    } else {
        System.err.println("downloading project $projectId from scratch.mit.edu")
        val download =
            try {
                ScratchDownloader(json).download(projectId)
            } catch (e: DownloadException) {
                fail("download failed: ${e.message}")
            }
        for (w in download.warnings) System.err.println("warning: $w")
        System.err.println("downloaded '${download.title}' by ${download.author} (${download.sb3.size / 1024} KiB)")
        saveSb3?.let {
            it.absoluteFile.parentFile?.mkdirs()
            it.writeBytes(download.sb3)
            System.err.println("wrote ${it.path}")
        }
        sb3 = download.sb3
        outFile = output ?: File("$projectId.jar")
    }

    val runtimeJar = if (includeRuntime) loadRuntimeJar() else null
    val result =
        try {
            JScratch.compile(sb3, runtimeJar, json)
        } catch (e: Exception) {
            fail("compilation failed: ${e.message}")
        }
    for (w in result.warnings) System.err.println("warning: $w")
    if (dump) {
        for ((name, bytes) in result.classes) {
            println("// ==== $name")
            println(JScratch.disassemble(bytes))
        }
    }
    outFile.parentFile?.mkdirs()
    outFile.writeBytes(result.jar)
    val targets = result.project.targets.size
    System.err.println("wrote ${outFile.path} (${result.jar.size / 1024} KiB, $targets targets)")

    if (run) {
        if (!includeRuntime) fail("--run needs the runtime; drop --no-runtime")
        val java = File(System.getProperty("java.home"), "bin/java").path
        val process = ProcessBuilder(java, "-jar", outFile.absolutePath).inheritIO().start()
        exitProcess(process.waitFor())
    }
}

private fun loadRuntimeJar(): ByteArray {
    val stream =
        object {}.javaClass.getResourceAsStream("/org/jscratch/cli/jscratch-runtime.jar")
            ?: fail("the embedded runtime JAR is missing from this build")
    return stream.use { it.readBytes() }
}

private fun fail(message: String): Nothing {
    System.err.println("jscratch: $message")
    exitProcess(2)
}
