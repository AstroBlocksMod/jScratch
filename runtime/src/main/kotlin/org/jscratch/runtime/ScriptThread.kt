package org.jscratch.runtime

import java.util.concurrent.Semaphore

/** Thrown inside a script to unwind it when the script is stopped. */
class StopScript : RuntimeException(null, null, false, false)

/**
 * One running Scratch script.
 *
 * Scratch scripts are cooperative green threads: a script runs until it reaches
 * a yield point (end of a loop iteration, a wait, a glide), then the next script
 * runs. jScratch maps each script onto a JVM virtual thread and hands control
 * back and forth with two semaphores, so exactly one script runs at any time
 * and the scheduler decides the order. This keeps generated bytecode simple:
 * a `forever` loop really is a loop with a call to `yieldLoop()` at the end.
 */
class ScriptThread(
    val runtime: Runtime,
    val target: Target,
    val scriptId: Int,
    /** Whether the script starts with an edge-activated hat, whose condition decides whether it runs at all. */
    private val edgeHat: Boolean = false,
) {
    // Made in [start], so a hat that does not fire allocates nothing but this object.
    private lateinit var runPermit: Semaphore
    private lateinit var yieldPermit: Semaphore

    @Volatile var done: Boolean = false
        private set

    @Volatile var killed: Boolean = false

    /** Set when the script yielded until the next frame (`wait`, `glide`) instead of a loop yield. */
    var tickYield: Boolean = false

    var warpDepth: Int = 0
    var warpStartNanos: Long = 0

    private var started = false

    /**
     * Starts the virtual thread the first time the script steps. An edge-activated hat checks its
     * condition first, on the scheduler thread like scratch-vm checks it at that point in the frame, so
     * a hat that does not fire, which is most of them in most frames, never needs a thread.
     */
    private fun start(): Boolean {
        started = true
        if (killed || (edgeHat && !target.edgeActivated(scriptId))) {
            done = true
            return false
        }
        runPermit = Semaphore(0)
        yieldPermit = Semaphore(0)
        Thread.ofVirtual().name("script-${target.name}-$scriptId").start {
            current.set(this)
            runPermit.acquireUninterruptibly()
            try {
                if (!killed) target.runScript(scriptId)
            } catch (_: StopScript) {
                // normal termination
            } catch (t: Throwable) {
                Log.warn("Script $scriptId in '${target.name}' crashed: $t")
                t.printStackTrace()
            } finally {
                done = true
                yieldPermit.release()
            }
        }
        return true
    }

    /** Called by the scheduler: lets the script run until it yields or finishes. */
    fun step() {
        if (done) return
        if (!started && !start()) return
        tickYield = false
        runPermit.release()
        yieldPermit.acquireUninterruptibly()
    }

    /** Called from inside the script: hands control back to the scheduler. */
    fun yieldNow(untilNextTick: Boolean) {
        if (warpDepth > 0) {
            // "Run without screen refresh": keep going, but never hog the frame for more than 500 ms.
            if (System.nanoTime() - warpStartNanos < WARP_TIME_NANOS) {
                if (killed) throw StopScript()
                return
            }
            tickYield = true
            yieldPermit.release()
            runPermit.acquireUninterruptibly()
            warpStartNanos = System.nanoTime()
            if (killed) throw StopScript()
            return
        }
        tickYield = untilNextTick
        yieldPermit.release()
        runPermit.acquireUninterruptibly()
        if (killed) throw StopScript()
    }

    /** Called from inside the script: waits for the next frame, in warp mode too. */
    fun yieldFrame() {
        tickYield = true
        yieldPermit.release()
        runPermit.acquireUninterruptibly()
        if (warpDepth > 0) warpStartNanos = System.nanoTime()
        if (killed) throw StopScript()
    }

    fun enterWarp() {
        if (warpDepth == 0) warpStartNanos = System.nanoTime()
        warpDepth++
    }

    fun exitWarp() {
        if (warpDepth > 0) warpDepth--
    }

    companion object {
        private const val WARP_TIME_NANOS = 500_000_000L
        private val current = ThreadLocal<ScriptThread?>()

        /** The script running on the calling thread, or null when called from the scheduler or UI. */
        @JvmStatic
        fun current(): ScriptThread? = current.get()
    }
}
